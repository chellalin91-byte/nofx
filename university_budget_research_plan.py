    def print_plan(self):
        """طباعة الخطة بشكل منسق"""
        plan = self.generate_complete_plan()
        
        print("=" * 80)
        print(plan["metadata"]["title"].center(80))
        print("=" * 80)
        print(f"\n{plan['metadata']['researcher']}")
        print(f"{plan['metadata']['institution']}")
        print(f"التاريخ: {plan['metadata']['date']}")
        print(f"نوع البحث: {plan['metadata']['research_type']}")
        print("\n" + "=" * 80 + "\n")
        
        for section in plan["sections"]:
            print(f"\n{'#' * 3} {section['title']}")
            print("-" * 80)
            self._print_section_content(section)
            print("\n")
    
    def _print_section_content(self, section: Dict, indent: int = 0):
        """طباعة محتوى القسم بشكل متدرج"""
        indent_str = "  " * indent
        
        for key, value in section.items():
            if key == "title":
                continue
            
            if isinstance(value, str):
                print(f"{indent_str}{value}")
            elif isinstance(value, list):
                for item in value:
                    if isinstance(item, str):
                        print(f"{indent_str}• {item}")
                    elif isinstance(item, dict):
                        self._print_section_content(item, indent + 1)
            elif isinstance(value, dict):
                if key not in ["metadata"]:
                    print(f"\n{indent_str}** {key} **")
                    self._print_section_content(value, indent + 1)


